export type IconName = keyof typeof icons;
export function Icon({
  name,
  size = 20,
  className = '',
}: {
  name: string;
  size?: number;
  className?: string;
}) {
  const C = icons[name as IconName] ?? Sparkles;
  return <C size={size} strokeWidth={1.7} aria-hidden="true" className={className} />;
}
